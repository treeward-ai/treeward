#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export PATH="$HOME/bin:$HOME/opt/go/bin:$HOME/go-sdk/bin:$HOME/sdk/go/bin:$PATH"

CLUSTER_NAME="${TREEWARD_CLUSTER_NAME:-treeward-quickstart}"
CONTEXT="kind-${CLUSTER_NAME}"
NAMESPACE="${TREEWARD_NAMESPACE:-treeward}"
IMAGE="${TREEWARD_IMAGE:-treeward:quickstart}"
STATE_DIR="${ROOT}/.treeward"
ENV_FILE="${STATE_DIR}/quickstart.env"
PF_PIDFILE="${STATE_DIR}/port-forward.pid"
PF_LOGFILE="${STATE_DIR}/port-forward.log"

# Preserve any caller-provided environment overrides before sourcing state.
CALLER_ENROLL="${TREEWARD_ENROLL_TOKEN:-}"
CALLER_ADMIN_BOOTSTRAP="${TREEWARD_ADMIN_BOOTSTRAP_TOKEN:-}"
CALLER_LOCAL="${TREEWARD_LOCAL_TOKEN:-}"
CALLER_TOKEN="${TREEWARD_TOKEN:-}"
CALLER_API_PORT="${TREEWARD_API_PORT:-}"

log()  { printf '[quickstart] %s\n' "$*"; }
warn() { printf '[quickstart] WARN: %s\n' "$*" >&2; }
die()  { printf '[quickstart] ERROR: %s\n' "$*" >&2; exit 1; }

check_prereqs() {
  local missing=0
  if ! command -v docker >/dev/null 2>&1; then
    printf '  missing: docker   -> https://docs.docker.com/get-docker/\n' >&2
    missing=1
  fi
  if ! command -v kind >/dev/null 2>&1; then
    printf '  missing: kind     -> https://kind.sigs.k8s.io/docs/user/quick-start/#installation\n' >&2
    missing=1
  fi
  if ! command -v kubectl >/dev/null 2>&1; then
    printf '  missing: kubectl  -> https://kubernetes.io/docs/tasks/tools/\n' >&2
    missing=1
  fi
  if ! command -v curl >/dev/null 2>&1; then
    printf '  missing: curl     -> install via your OS package manager (e.g. apt install curl)\n' >&2
    missing=1
  fi
  if [[ "$missing" -ne 0 ]]; then
    die "Missing required prerequisites (see install hints above)."
  fi
  if ! docker info >/dev/null 2>&1; then
    die "Docker daemon is not reachable. Start Docker (or Docker Desktop) and retry."
  fi
}

gen_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    od -An -tx1 -N32 /dev/urandom | tr -d ' \n'
  fi
}

write_env_file() {
  local tmp_file
  umask 077
  mkdir -p "$STATE_DIR"
  chmod 700 "$STATE_DIR"
  tmp_file="${ENV_FILE}.tmp.$$"
  cat >"$tmp_file" <<EOF
# Generated by treeward quickstart (mode 0600, gitignored)
TREEWARD_CLUSTER_NAME=${CLUSTER_NAME}
TREEWARD_API_PORT=${API_PORT}
TREEWARD_API_URL=${API_URL}
TREEWARD_ENROLL_TOKEN=${ENROLL_TOKEN}
TREEWARD_ADMIN_BOOTSTRAP_TOKEN=${ADMIN_BOOTSTRAP_TOKEN}
TREEWARD_LOCAL_TOKEN=${LOCAL_TOKEN}
TREEWARD_TOKEN=${OPERATOR_TOKEN}
EOF
  chmod 600 "$tmp_file"
  mv -f "$tmp_file" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
}

load_or_init_secrets() {
  mkdir -p "$STATE_DIR"
  chmod 700 "$STATE_DIR"

  local saved_enroll="" saved_admin_bootstrap="" saved_local="" saved_token="" saved_port=""
  if [[ -f "$ENV_FILE" ]]; then
    chmod 600 "$ENV_FILE"
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    saved_enroll="${TREEWARD_ENROLL_TOKEN:-}"
    saved_admin_bootstrap="${TREEWARD_ADMIN_BOOTSTRAP_TOKEN:-}"
    saved_local="${TREEWARD_LOCAL_TOKEN:-}"
    saved_token="${TREEWARD_TOKEN:-}"
    saved_port="${TREEWARD_API_PORT:-}"
  fi

  API_PORT="${CALLER_API_PORT:-${saved_port:-8080}}"
  API_URL="http://127.0.0.1:${API_PORT}"

  if [[ -n "$CALLER_ENROLL" ]]; then
    ENROLL_TOKEN="$CALLER_ENROLL"
  elif [[ -n "$saved_enroll" ]]; then
    ENROLL_TOKEN="$saved_enroll"
  else
    ENROLL_TOKEN="$(gen_secret)"
  fi

  if [[ -n "$CALLER_ADMIN_BOOTSTRAP" ]]; then
    ADMIN_BOOTSTRAP_TOKEN="$CALLER_ADMIN_BOOTSTRAP"
  elif [[ -n "$saved_admin_bootstrap" ]]; then
    ADMIN_BOOTSTRAP_TOKEN="$saved_admin_bootstrap"
  else
    ADMIN_BOOTSTRAP_TOKEN="$(gen_secret)"
  fi

  if [[ "$ENROLL_TOKEN" == "$ADMIN_BOOTSTRAP_TOKEN" ]]; then
    die "TREEWARD_ENROLL_TOKEN and TREEWARD_ADMIN_BOOTSTRAP_TOKEN must be distinct secrets."
  fi

  if [[ -n "$CALLER_LOCAL" ]]; then
    LOCAL_TOKEN="$CALLER_LOCAL"
  elif [[ -n "$saved_local" ]]; then
    LOCAL_TOKEN="$saved_local"
  else
    LOCAL_TOKEN="$(gen_secret)"
  fi

  if [[ -n "$CALLER_TOKEN" ]]; then
    OPERATOR_TOKEN="$CALLER_TOKEN"
  elif [[ -n "$saved_token" ]]; then
    OPERATOR_TOKEN="$saved_token"
  else
    OPERATOR_TOKEN=""
  fi

  write_env_file
  log "Secrets initialized in .treeward/quickstart.env (mode 0600)"
}

ensure_cluster() {
  if kind get clusters 2>/dev/null | grep -Fxq "$CLUSTER_NAME"; then
    log "Kind cluster '${CLUSTER_NAME}' already exists; reusing."
  else
    log "Creating Kind cluster '${CLUSTER_NAME}'..."
    kind create cluster --name "$CLUSTER_NAME" --wait 60s
  fi
  if ! kubectl config get-contexts "$CONTEXT" >/dev/null 2>&1; then
    kind export kubeconfig --name "$CLUSTER_NAME"
  fi
}

install_cli() {
  mkdir -p "$ROOT/bin"
  local host_os host_arch image_platform
  host_os="$(uname -s | tr '[:upper:]' '[:lower:]')"
  case "$(uname -m)" in
    x86_64|amd64) host_arch="amd64" ;;
    aarch64|arm64) host_arch="arm64" ;;
    *) host_arch="$(uname -m)" ;;
  esac
  image_platform="$(docker image inspect --format '{{.Os}}/{{.Architecture}}' "$IMAGE" 2>/dev/null || true)"

  if [[ "${host_os}/${host_arch}" == "${image_platform}" ]]; then
    log "Extracting local treeward CLI from '${IMAGE}' (${image_platform})..."
    local cid
    cid="$(docker create "$IMAGE")"
    if ! docker cp "${cid}:/app/treeward" "$ROOT/bin/treeward"; then
      docker rm -f "$cid" >/dev/null 2>&1 || true
      die "Failed to extract /app/treeward from '${IMAGE}'."
    fi
    docker rm -f "$cid" >/dev/null
    chmod +x "$ROOT/bin/treeward"
    return 0
  fi

  if command -v go >/dev/null 2>&1; then
    log "Host platform (${host_os}/${host_arch}) differs from image (${image_platform:-unknown}); building local treeward CLI with go..."
    (cd "$ROOT" && CGO_ENABLED=0 go build -o "$ROOT/bin/treeward" ./cmd/treeward)
    return 0
  fi

  die "Host platform (${host_os}/${host_arch}) does not match container image (${image_platform:-unknown}) and 'go' is not installed to build ./bin/treeward."
}

build_and_load() {
  log "Building container image '${IMAGE}'..."
  docker build -t "$IMAGE" "$ROOT"
  log "Loading '${IMAGE}' into Kind cluster '${CLUSTER_NAME}'..."
  kind load docker-image "$IMAGE" --name "$CLUSTER_NAME"
  install_cli
}

deploy_manifests() {
  log "Applying namespace, secrets, and manifests to '${CONTEXT}'..."
  kubectl --context "$CONTEXT" create namespace "$NAMESPACE" --dry-run=client -o yaml \
    | kubectl --context "$CONTEXT" apply -f - >/dev/null

  local prev_enroll_rv prev_admin_bootstrap_rv prev_local_rv
  prev_enroll_rv="$(kubectl --context "$CONTEXT" -n "$NAMESPACE" get secret treeward-enroll -o jsonpath='{.metadata.resourceVersion}' 2>/dev/null || true)"
  prev_admin_bootstrap_rv="$(kubectl --context "$CONTEXT" -n "$NAMESPACE" get secret treeward-admin-bootstrap -o jsonpath='{.metadata.resourceVersion}' 2>/dev/null || true)"
  prev_local_rv="$(kubectl --context "$CONTEXT" -n "$NAMESPACE" get secret treeward-local -o jsonpath='{.metadata.resourceVersion}' 2>/dev/null || true)"

  # Apply secrets via stdin so token values never appear in stdout or process args.
  kubectl --context "$CONTEXT" apply -f - >/dev/null <<EOF
apiVersion: v1
kind: Secret
metadata:
  name: treeward-enroll
  namespace: ${NAMESPACE}
type: Opaque
stringData:
  token: "${ENROLL_TOKEN}"
---
apiVersion: v1
kind: Secret
metadata:
  name: treeward-admin-bootstrap
  namespace: ${NAMESPACE}
type: Opaque
stringData:
  token: "${ADMIN_BOOTSTRAP_TOKEN}"
---
apiVersion: v1
kind: Secret
metadata:
  name: treeward-local
  namespace: ${NAMESPACE}
type: Opaque
stringData:
  token: "${LOCAL_TOKEN}"
EOF

  local new_enroll_rv new_admin_bootstrap_rv new_local_rv
  new_enroll_rv="$(kubectl --context "$CONTEXT" -n "$NAMESPACE" get secret treeward-enroll -o jsonpath='{.metadata.resourceVersion}' 2>/dev/null || true)"
  new_admin_bootstrap_rv="$(kubectl --context "$CONTEXT" -n "$NAMESPACE" get secret treeward-admin-bootstrap -o jsonpath='{.metadata.resourceVersion}' 2>/dev/null || true)"
  new_local_rv="$(kubectl --context "$CONTEXT" -n "$NAMESPACE" get secret treeward-local -o jsonpath='{.metadata.resourceVersion}' 2>/dev/null || true)"

  kubectl --context "$CONTEXT" apply -f "$ROOT/deploy/k8s/treeward.yaml"

  if [[ ( -n "$prev_enroll_rv" && "$prev_enroll_rv" != "$new_enroll_rv" ) || ( -n "$prev_admin_bootstrap_rv" && "$prev_admin_bootstrap_rv" != "$new_admin_bootstrap_rv" ) || ( -n "$prev_local_rv" && "$prev_local_rv" != "$new_local_rv" ) ]]; then
    log "Detected secret rotation; restarting workloads to pick up new tokens..."
    kubectl --context "$CONTEXT" -n "$NAMESPACE" rollout restart \
      deploy/treeward-api deploy/treeward-connector ds/treeward-agent
  fi

  log "Waiting for rollouts..."
  kubectl --context "$CONTEXT" -n "$NAMESPACE" rollout status deploy/treeward-api --timeout=120s
  kubectl --context "$CONTEXT" -n "$NAMESPACE" rollout status deploy/treeward-connector --timeout=120s
  kubectl --context "$CONTEXT" -n "$NAMESPACE" rollout status ds/treeward-agent --timeout=120s
}

is_port_in_use() {
  local port="$1"
  (exec 3<>/dev/tcp/127.0.0.1/"$port") 2>/dev/null
}

start_port_forward() {
  if [[ -f "$PF_PIDFILE" ]]; then
    local existing_pid
    existing_pid="$(cat "$PF_PIDFILE" 2>/dev/null || true)"
    if [[ -n "$existing_pid" ]] && kill -0 "$existing_pid" 2>/dev/null; then
      if curl -fsS --max-time 2 "${API_URL}/healthz" >/dev/null 2>&1; then
        log "Reusing existing port-forward to ${API_URL} (pid ${existing_pid})."
        return 0
      fi
      # Stale/broken port-forward managed by us; restart it.
      kill "$existing_pid" 2>/dev/null || true
      sleep 1
    fi
    rm -f "$PF_PIDFILE"
  fi

  if is_port_in_use "$API_PORT"; then
    die "127.0.0.1:${API_PORT} is already in use by another process (not managed by quickstart). Stop that process or run: TREEWARD_API_PORT=18080 make quickstart"
  fi

  log "Starting background port-forward to ${API_URL}..."
  nohup kubectl --context "$CONTEXT" -n "$NAMESPACE" port-forward \
    --address 127.0.0.1 svc/treeward-api "${API_PORT}:8080" \
    >"$PF_LOGFILE" 2>&1 </dev/null &
  local pf_pid=$!
  echo "$pf_pid" >"$PF_PIDFILE"

  local i
  for i in $(seq 1 30); do
    if ! kill -0 "$pf_pid" 2>/dev/null; then
      cat "$PF_LOGFILE" >&2 || true
      rm -f "$PF_PIDFILE"
      die "Port-forward exited unexpectedly."
    fi
    if curl -fsS --max-time 2 "${API_URL}/healthz" >/dev/null 2>&1; then
      log "Port-forward ready at ${API_URL} (pid ${pf_pid})."
      return 0
    fi
    sleep 1
  done

  cat "$PF_LOGFILE" >&2 || true
  die "Timed out waiting for API healthz via port-forward at ${API_URL}."
}

mint_operator_token() {
  if [[ -n "$OPERATOR_TOKEN" ]]; then
    local code
    code="$(curl -sS -o /dev/null -w '%{http_code}' \
      -H "Authorization: Bearer ${OPERATOR_TOKEN}" \
      "${API_URL}/v1/nodes" || true)"
    if [[ "$code" == "200" ]]; then
      log "Reusing valid operator token from .treeward/quickstart.env."
      write_env_file
      return 0
    fi
    log "Saved operator token is no longer valid (HTTP ${code}); minting a fresh token..."
  fi

  log "Minting operator token via API..."
  local resp_file http_code
  resp_file="$(mktemp)"
  chmod 600 "$resp_file"
  http_code="$(curl -sS -o "$resp_file" -w '%{http_code}' \
    -X POST \
    -H "Content-Type: application/json" \
    -H "Authorization: Bearer ${ADMIN_BOOTSTRAP_TOKEN}" \
    -d '{"name":"quickstart-operator"}' \
    "${API_URL}/v1/tokens" || true)"

  if [[ "$http_code" != "201" ]]; then
    rm -f "$resp_file"
    die "Failed to mint operator token (HTTP ${http_code}). Ensure Secret/treeward-admin-bootstrap matches TREEWARD_ADMIN_BOOTSTRAP_TOKEN."
  fi

  OPERATOR_TOKEN="$(sed -n 's/.*"token"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$resp_file" | head -n1)"
  rm -f "$resp_file"

  if [[ -z "$OPERATOR_TOKEN" ]]; then
    die "API returned HTTP 201 for /v1/tokens but token field could not be parsed."
  fi

  write_env_file
  log "Operator token saved to .treeward/quickstart.env (mode 0600)."
}

print_next_steps() {
  cat <<EOF

========================================================================
Treeward quickstart is ready! (stub agents — no eBPF / kernel enforcement)
========================================================================
Cluster:    ${CLUSTER_NAME} (kubectl --context ${CONTEXT} -n ${NAMESPACE})
API URL:    ${API_URL}
State file: .treeward/quickstart.env (mode 0600, gitignored)

Next steps:
  # Load API URL and operator token into your shell
  set -a; source .treeward/quickstart.env; set +a

  # Inspect the fleet and audit log
  ./bin/treeward nodes
  ./bin/treeward bindings
  ./bin/treeward audit

  # Re-run the demo anytime
  make demo

  # Check cluster pods/logs
  make status
  make logs

  # Tear down the quickstart cluster and local state
  make teardown
EOF
}

main() {
  check_prereqs
  load_or_init_secrets
  ensure_cluster
  build_and_load
  deploy_manifests
  start_port_forward
  mint_operator_token

  log "Running demo flow..."
  "$ROOT/scripts/demo.sh"

  print_next_steps
}

main "$@"
